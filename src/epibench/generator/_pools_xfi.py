from __future__ import annotations

from datetime import date
from typing import Any, Dict, List


def compute_forecast_gold(events: List[Dict[str, Any]]) -> Dict[str, Any]:
    """Compute exact move_count and total_slip_days from structured ISO event dates."""
    commitments = [e for e in events if e.get("event_kind") == "commitment"]
    slips = [e for e in events if e.get("event_kind") == "slip"]
    completions = [e for e in events if e.get("event_kind") == "completion"]

    if len(commitments) != 1:
        raise ValueError(f"Expected exactly 1 commitment event, got {len(commitments)}")
    if len(completions) != 1:
        raise ValueError(f"Expected exactly 1 completion event, got {len(completions)}")

    initial_target = date.fromisoformat(commitments[0]["target_date"])
    final_completion = date.fromisoformat(completions[0]["target_date"])
    total_slip_days = (final_completion - initial_target).days
    if total_slip_days < 0:
        raise ValueError(
            f"Completion date {final_completion} precedes initial target {initial_target}"
        )

    return {
        "initial_target_date": initial_target.isoformat(),
        "final_completion_date": final_completion.isoformat(),
        "move_count": len(slips),
        "total_slip_days": total_slip_days,
    }


